function semanticTokenColors(s) {
  return {
    namespace: s.namespace,
    class: s.type,
    "class.declaration": { foreground: s.type, bold: true },
    "class.defaultLibrary": s.type,
    enum: s.type,
    enumMember: s.constant,
    interface: s.interface,
    struct: s.type,
    typeParameter: s.interface,
    type: s.type,
    "type.defaultLibrary": s.type,
    parameter: { foreground: s.parameter, italic: true },
    variable: s.variable,
    "variable.readonly": s.constant,
    "variable.defaultLibrary": s.constant,
    "variable.readonly.defaultLibrary": s.constant,
    property: s.property,
    "property.readonly": s.constant,
    "property.declaration": s.property,
    function: s.func,
    "function.declaration": { foreground: s.func, bold: true },
    "function.defaultLibrary": s.func,
    method: s.func,
    "method.declaration": { foreground: s.func, bold: true },
    macro: s.decorator,
    decorator: { foreground: s.decorator, italic: true },
    keyword: s.keyword,
    modifier: s.storage,
    comment: { foreground: s.comment, italic: true },
    string: s.string,
    number: s.number,
    regexp: s.regex,
    operator: s.operator,
    event: s.constant,
    label: s.markupHeading,
    "*.deprecated": { strikethrough: true },
    "*.static": { italic: true },
    "*.abstract": { italic: true },
  };
}

// ---------------------------------------------------------------------------
// Build
// ---------------------------------------------------------------------------
function build() {
  const outDir = path.join(__dirname, "..", "themes");
  fs.mkdirSync(outDir, { recursive: true });

  for (const v of Object.values(variants)) {
    const ui = { ...v.ui, __ansi: v.ansi };
    const colors = workbench(ui, v.type);
    for (const k of Object.keys(colors)) if (colors[k] === undefined) delete colors[k];

    const theme = {
      $schema: "vscode://schemas/color-theme",
      name: v.name,
      type: v.type,
      semanticHighlighting: true,
      colors,
      semanticTokenColors: semanticTokenColors(v.syntax),
      tokenColors: tokenColors(v.syntax),
    };

    const target = path.join(outDir, v.file);
    fs.writeFileSync(target, JSON.stringify(theme, null, 2) + "\n");
    console.log(`✈  ${v.name.padEnd(30)} → themes/${v.file} (${Object.keys(colors).length} workbench colours, ${theme.tokenColors.length} token rules)`);
  }
}

build();
